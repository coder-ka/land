use std::collections::{HashMap, HashSet};

use crate::CompileError;
use crate::ast::{BinaryOperator, Type, UnaryOperator};
use crate::semantic::{
    Expression, ExpressionKind, Function, FunctionId, LocalId, Pattern, PatternKind, Program,
    Statement,
};

pub fn generate(program: &Program) -> Result<String, CompileError> {
    let mut output = String::from("; generated by landc\n\n");

    for function in &program.functions {
        if function.type_parameters.is_empty() {
            generate_function(
                function,
                program,
                &HashMap::new(),
                &function.name,
                &mut output,
            );
        }
    }
    for (function_id, arguments) in discover_specializations(program)? {
        let function = &program.functions[function_id];
        let substitutions = substitutions(function, &arguments);
        let symbol = specialized_symbol(function, &arguments);
        generate_function(function, program, &substitutions, &symbol, &mut output);
    }
    Ok(output)
}

fn generate_function(
    function: &Function,
    program: &Program,
    substitutions: &HashMap<String, Type>,
    symbol: &str,
    output: &mut String,
) {
    let return_type = function.return_type.substitute(substitutions);
    let parameters = function
        .parameters
        .iter()
        .map(|parameter| {
            format!(
                "{} %{}",
                llvm_type(&parameter.parameter_type.substitute(substitutions)),
                parameter.name
            )
        })
        .collect::<Vec<_>>()
        .join(", ");
    let Some(body) = &function.body else {
        output.push_str(&format!(
            "declare {} @{}({parameters})\n\n",
            llvm_type(&return_type),
            symbol
        ));
        return;
    };

    let mut generator = FunctionGenerator {
        program,
        substitutions,
        output: String::new(),
        allocations: String::new(),
        locals: Vec::with_capacity(function.locals.len()),
        next_register: 0,
        next_label: 0,
        next_slot: 0,
    };
    for local in &function.locals {
        let value_type = local.value_type.substitute(substitutions);
        let local = generator.declare_local(&local.name, value_type);
        generator.locals.push(local);
    }
    for parameter in &function.parameters {
        let parameter_type = parameter.parameter_type.substitute(substitutions);
        let local = generator.local(parameter.local).clone();
        generator.output.push_str(&format!(
            "  store {} %{}, {}* %{}\n",
            llvm_type(&parameter_type),
            parameter.name,
            llvm_type(&parameter_type),
            local.slot
        ));
    }
    generator.generate_block(body);
    output.push_str(&format!(
        "define {} @{}({parameters}) {{\nentry:\n",
        llvm_type(&return_type),
        symbol
    ));
    output.push_str(&generator.allocations);
    output.push_str(&generator.output);
    output.push_str("}\n\n");
}

struct FunctionGenerator<'a> {
    output: String,
    allocations: String,
    program: &'a Program,
    substitutions: &'a HashMap<String, Type>,
    locals: Vec<Local>,
    next_register: usize,
    next_label: usize,
    next_slot: usize,
}

impl FunctionGenerator<'_> {
    fn generate_block(&mut self, statements: &[Statement]) -> bool {
        let mut terminated = false;
        for statement in statements {
            if terminated {
                break;
            }
            terminated = self.generate_statement(statement);
        }
        terminated
    }

    fn generate_statement(&mut self, statement: &Statement) -> bool {
        match statement {
            Statement::Let { pattern, value } => {
                let value = self.generate_expression(value);
                self.bind_pattern(pattern, &value);
                false
            }
            Statement::Assign { local, value } => {
                let target = self.local(*local).clone();
                let value = self.generate_expression(value);
                self.store(&target, &value);
                false
            }
            Statement::Expression(expression) => {
                self.generate_expression(expression);
                false
            }
            Statement::Return(value) => {
                if let Some(expression) = value {
                    let value = self.generate_expression(expression);
                    self.output.push_str(&format!(
                        "  ret {} {}\n",
                        llvm_type(&value.value_type),
                        value.operand()
                    ));
                } else {
                    self.output.push_str("  ret void\n");
                }
                true
            }
            Statement::If {
                condition,
                then_body,
                else_body,
            } => self.generate_if(condition, then_body, else_body.as_deref()),
            Statement::For { condition, body } => self.generate_for(condition, body),
        }
    }

    fn generate_if(
        &mut self,
        condition: &Expression,
        then_body: &[Statement],
        else_body: Option<&[Statement]>,
    ) -> bool {
        let condition = self.generate_expression(condition);
        let then_label = self.allocate_label("then");
        let else_label = self.allocate_label(if else_body.is_some() { "else" } else { "end" });
        let end_label = else_body.map(|_| self.allocate_label("end"));
        self.output.push_str(&format!(
            "  br i1 {}, label %{then_label}, label %{else_label}\n\n{then_label}:\n",
            condition.operand()
        ));

        let then_terminated = self.generate_block(then_body);
        let continuation = end_label.as_deref().unwrap_or(&else_label);
        if !then_terminated {
            self.output
                .push_str(&format!("  br label %{continuation}\n"));
        }

        if let Some(else_body) = else_body {
            self.output.push_str(&format!("\n{else_label}:\n"));
            let else_terminated = self.generate_block(else_body);
            if !else_terminated {
                self.output
                    .push_str(&format!("  br label %{continuation}\n"));
            }
            if then_terminated && else_terminated {
                return true;
            }
            self.output.push_str(&format!("\n{continuation}:\n"));
        } else {
            self.output.push_str(&format!("\n{else_label}:\n"));
        }
        false
    }

    fn generate_for(&mut self, condition: &Expression, body: &[Statement]) -> bool {
        if matches!(&condition.kind, ExpressionKind::Boolean(false)) {
            return false;
        }
        if matches!(&condition.kind, ExpressionKind::Boolean(true)) {
            let body_label = self.allocate_label("for.body");
            self.output
                .push_str(&format!("  br label %{body_label}\n\n{body_label}:\n"));
            let body_terminated = self.generate_block(body);
            if !body_terminated {
                self.output.push_str(&format!("  br label %{body_label}\n"));
            }
            return true;
        }
        let condition_label = self.allocate_label("for.condition");
        let body_label = self.allocate_label("for.body");
        let end_label = self.allocate_label("for.end");
        self.output.push_str(&format!(
            "  br label %{condition_label}\n\n{condition_label}:\n"
        ));
        let condition_value = self.generate_expression(condition);
        self.output.push_str(&format!(
            "  br i1 {}, label %{body_label}, label %{end_label}\n\n{body_label}:\n",
            condition_value.operand()
        ));
        let body_terminated = self.generate_block(body);
        if !body_terminated {
            self.output
                .push_str(&format!("  br label %{condition_label}\n"));
        }
        self.output.push_str(&format!("\n{end_label}:\n"));
        false
    }

    fn generate_expression(&mut self, expression: &Expression) -> TypedValue {
        let result_type = expression.result_type.substitute(self.substitutions);
        match &expression.kind {
            ExpressionKind::Integer(value) => TypedValue {
                value_type: result_type,
                value: Value::Integer(*value),
            },
            ExpressionKind::Boolean(value) => TypedValue {
                value_type: result_type,
                value: Value::Boolean(*value),
            },
            ExpressionKind::Local(local) => {
                let local = self.local(*local).clone();
                let register = self.allocate_register();
                self.output.push_str(&format!(
                    "  %{register} = load {}, {}* %{}\n",
                    llvm_type(&local.value_type),
                    llvm_type(&local.value_type),
                    local.slot
                ));
                TypedValue {
                    value_type: result_type,
                    value: Value::Register(register),
                }
            }
            ExpressionKind::Function(function) => TypedValue {
                value_type: result_type,
                value: Value::Function(self.program.functions[*function].name.clone()),
            },
            ExpressionKind::DirectCall {
                function,
                type_arguments,
                arguments,
            } => self.generate_direct_call(*function, type_arguments, arguments, result_type),
            ExpressionKind::IndirectCall { callee, arguments } => {
                self.generate_indirect_call(callee, arguments, result_type)
            }
            ExpressionKind::Tuple(values) => self.generate_tuple(values, result_type),
            ExpressionKind::Array(values) => self.generate_array(values, result_type),
            ExpressionKind::Index { base, index } => self.generate_index(base, index, result_type),
            ExpressionKind::Unary {
                operator: UnaryOperator::Negate,
                operand,
            } => {
                if let ExpressionKind::Integer(value) = operand.kind {
                    return TypedValue {
                        value_type: result_type,
                        value: Value::Integer(-value),
                    };
                }
                let operand = self.generate_expression(operand);
                let register = self.allocate_register();
                self.output.push_str(&format!(
                    "  %{register} = sub {} 0, {}\n",
                    llvm_type(&operand.value_type),
                    operand.operand()
                ));
                TypedValue {
                    value_type: result_type,
                    value: Value::Register(register),
                }
            }
            ExpressionKind::Binary {
                operator,
                left,
                right,
            } => self.generate_binary(*operator, left, right, result_type),
        }
    }

    fn generate_tuple(&mut self, values: &[Expression], tuple_type: Type) -> TypedValue {
        let generated = values
            .iter()
            .map(|value| self.generate_expression(value))
            .collect::<Vec<_>>();
        let mut aggregate = Value::Undef;
        for (index, value) in generated.iter().enumerate() {
            let register = self.allocate_register();
            self.output.push_str(&format!(
                "  %{register} = insertvalue {} {}, {} {}, {index}\n",
                llvm_type(&tuple_type),
                aggregate.operand(),
                llvm_type(&value.value_type),
                value.operand()
            ));
            aggregate = Value::Register(register);
        }
        TypedValue {
            value_type: tuple_type,
            value: aggregate,
        }
    }

    fn generate_array(&mut self, values: &[Expression], array_type: Type) -> TypedValue {
        let mut aggregate = Value::Undef;
        for (index, expression) in values.iter().enumerate() {
            let value = self.generate_expression(expression);
            let register = self.allocate_register();
            self.output.push_str(&format!(
                "  %{register} = insertvalue {} {}, {} {}, {index}\n",
                llvm_type(&array_type),
                aggregate.operand(),
                llvm_type(&value.value_type),
                value.operand()
            ));
            aggregate = Value::Register(register);
        }
        TypedValue {
            value_type: array_type,
            value: aggregate,
        }
    }

    fn generate_index(
        &mut self,
        base: &Expression,
        index: &Expression,
        result_type: Type,
    ) -> TypedValue {
        let base = self.generate_expression(base);
        let index = self.generate_expression(index);
        let slot = self.declare_local("array.index", base.value_type.clone());
        self.store(&slot, &base);
        let address = self.allocate_register();
        self.output.push_str(&format!(
            "  %{address} = getelementptr inbounds {}, {}* %{}, i32 0, i32 {}\n",
            llvm_type(&base.value_type),
            llvm_type(&base.value_type),
            slot.slot,
            index.operand()
        ));
        let value = self.allocate_register();
        self.output.push_str(&format!(
            "  %{value} = load {}, {}* %{address}\n",
            llvm_type(&result_type),
            llvm_type(&result_type)
        ));
        TypedValue {
            value_type: result_type,
            value: Value::Register(value),
        }
    }

    fn generate_direct_call(
        &mut self,
        function_id: FunctionId,
        type_arguments: &[Type],
        arguments: &[Expression],
        return_type: Type,
    ) -> TypedValue {
        let function = &self.program.functions[function_id];
        let concrete_arguments = type_arguments
            .iter()
            .map(|argument| argument.substitute(self.substitutions))
            .collect::<Vec<_>>();
        let symbol = if concrete_arguments.is_empty() {
            function.name.clone()
        } else {
            specialized_symbol(function, &concrete_arguments)
        };
        self.emit_call(&format!("@{symbol}"), arguments, return_type)
    }

    fn generate_indirect_call(
        &mut self,
        callee: &Expression,
        arguments: &[Expression],
        return_type: Type,
    ) -> TypedValue {
        let callee = self.generate_expression(callee);
        self.emit_call(&callee.operand(), arguments, return_type)
    }

    fn emit_call(
        &mut self,
        target: &str,
        arguments: &[Expression],
        return_type: Type,
    ) -> TypedValue {
        let operands = arguments
            .iter()
            .map(|argument| {
                let value = self.generate_expression(argument);
                format!("{} {}", llvm_type(&value.value_type), value.operand())
            })
            .collect::<Vec<_>>();
        let value = if return_type == Type::Void {
            self.output
                .push_str(&format!("  call void {target}({})\n", operands.join(", ")));
            Value::Void
        } else {
            let register = self.allocate_register();
            self.output.push_str(&format!(
                "  %{register} = call {} {target}({})\n",
                llvm_type(&return_type),
                operands.join(", ")
            ));
            Value::Register(register)
        };
        TypedValue {
            value_type: return_type,
            value,
        }
    }

    fn generate_binary(
        &mut self,
        operator: BinaryOperator,
        left: &Expression,
        right: &Expression,
        result_type: Type,
    ) -> TypedValue {
        let left = self.generate_expression(left);
        let right = self.generate_expression(right);
        let operand_type = left.value_type.clone();
        let signed = operand_type.is_signed_integer();
        let instruction = match operator {
            BinaryOperator::Add => "add",
            BinaryOperator::Subtract => "sub",
            BinaryOperator::Multiply => "mul",
            BinaryOperator::Divide => {
                if signed {
                    "sdiv"
                } else {
                    "udiv"
                }
            }
            BinaryOperator::Less => {
                if signed {
                    "icmp slt"
                } else {
                    "icmp ult"
                }
            }
            BinaryOperator::LessEqual => {
                if signed {
                    "icmp sle"
                } else {
                    "icmp ule"
                }
            }
            BinaryOperator::Greater => {
                if signed {
                    "icmp sgt"
                } else {
                    "icmp ugt"
                }
            }
            BinaryOperator::GreaterEqual => {
                if signed {
                    "icmp sge"
                } else {
                    "icmp uge"
                }
            }
            BinaryOperator::Equal => "icmp eq",
            BinaryOperator::NotEqual => "icmp ne",
        };
        let register = self.allocate_register();
        self.output.push_str(&format!(
            "  %{register} = {instruction} {} {}, {}\n",
            llvm_type(&operand_type),
            left.operand(),
            right.operand()
        ));
        TypedValue {
            value_type: result_type,
            value: Value::Register(register),
        }
    }

    fn bind_pattern(&mut self, pattern: &Pattern, value: &TypedValue) {
        match &pattern.kind {
            PatternKind::Bind(local) => {
                let slot = self.local(*local).clone();
                self.store(&slot, value);
            }
            PatternKind::Tuple(patterns) => {
                for (index, pattern) in patterns.iter().enumerate() {
                    let register = self.allocate_register();
                    self.output.push_str(&format!(
                        "  %{register} = extractvalue {} {}, {index}\n",
                        llvm_type(&value.value_type),
                        value.operand()
                    ));
                    self.bind_pattern(
                        pattern,
                        &TypedValue {
                            value_type: pattern.value_type.substitute(self.substitutions),
                            value: Value::Register(register),
                        },
                    );
                }
            }
        }
    }

    fn local(&self, local: LocalId) -> &Local {
        &self.locals[local]
    }

    fn declare_local(&mut self, name: &str, value_type: Type) -> Local {
        let slot = format!("{name}.addr.{}", self.next_slot);
        self.next_slot += 1;
        self.allocations
            .push_str(&format!("  %{slot} = alloca {}\n", llvm_type(&value_type)));
        Local { value_type, slot }
    }

    fn store(&mut self, local: &Local, value: &TypedValue) {
        self.output.push_str(&format!(
            "  store {} {}, {}* %{}\n",
            llvm_type(&local.value_type),
            value.operand(),
            llvm_type(&local.value_type),
            local.slot
        ));
    }

    fn allocate_register(&mut self) -> usize {
        let register = self.next_register;
        self.next_register += 1;
        register
    }

    fn allocate_label(&mut self, prefix: &str) -> String {
        let label = format!("{prefix}.{}", self.next_label);
        self.next_label += 1;
        label
    }
}

#[derive(Clone)]
struct Local {
    value_type: Type,
    slot: String,
}

struct TypedValue {
    value_type: Type,
    value: Value,
}

impl TypedValue {
    fn operand(&self) -> String {
        self.value.operand()
    }
}

enum Value {
    Integer(i128),
    Boolean(bool),
    Register(usize),
    Function(String),
    Void,
    Undef,
}

impl Value {
    fn operand(&self) -> String {
        match self {
            Self::Integer(value) => value.to_string(),
            Self::Boolean(value) => i32::from(*value).to_string(),
            Self::Register(register) => format!("%{register}"),
            Self::Function(name) => format!("@{name}"),
            Self::Void => "void".to_owned(),
            Self::Undef => "undef".to_owned(),
        }
    }
}

fn llvm_type(value_type: &Type) -> String {
    match value_type {
        Type::I8 | Type::U8 => "i8".to_owned(),
        Type::I16 | Type::U16 => "i16".to_owned(),
        Type::I32 | Type::U32 => "i32".to_owned(),
        Type::I64 | Type::U64 => "i64".to_owned(),
        Type::Bool => "i1".to_owned(),
        Type::Void => "void".to_owned(),
        Type::Tuple(elements) => format!(
            "{{ {} }}",
            elements
                .iter()
                .map(llvm_type)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        Type::Array(element, length) => format!("[{length} x {}]", llvm_type(element)),
        Type::Pointer(inner) => format!("{}*", llvm_type(inner)),
        Type::Linear(inner) => llvm_type(inner),
        Type::Function(parameters, result) => format!(
            "{} ({})*",
            llvm_type(result),
            parameters
                .iter()
                .map(llvm_type)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        Type::Parameter(name) => format!("%type.{name}"),
    }
}

type Specialization = (FunctionId, Vec<Type>);
const SPECIALIZATION_BUDGET: usize = 256;

fn discover_specializations(program: &Program) -> Result<Vec<Specialization>, CompileError> {
    let mut roots = Vec::new();
    for function in &program.functions {
        if function.type_parameters.is_empty()
            && let Some(body) = &function.body
        {
            collect_specializations(body, &HashMap::new(), program, &mut roots);
        }
    }
    let mut discovered = Vec::new();
    let mut seen = HashSet::new();
    let mut active = Vec::new();
    for (root, span) in roots {
        visit_specialization(root, span, program, &mut active, &mut seen, &mut discovered)?;
    }
    Ok(discovered)
}

fn visit_specialization(
    specialization: Specialization,
    span: crate::lexer::Span,
    program: &Program,
    active: &mut Vec<Specialization>,
    seen: &mut HashSet<Specialization>,
    discovered: &mut Vec<Specialization>,
) -> Result<(), CompileError> {
    if let Some(ancestor) = active
        .iter()
        .find(|ancestor| ancestor.0 == specialization.0)
    {
        if ancestor != &specialization {
            let name = &program.functions[specialization.0].name;
            return Err(CompileError::new(
                span.line,
                span.column,
                format!("polymorphic recursion changes the specialization of `{name}`"),
            ));
        }
        return Ok(());
    }
    if seen.contains(&specialization) {
        return Ok(());
    }
    if seen.len() >= SPECIALIZATION_BUDGET {
        return Err(CompileError::new(
            span.line,
            span.column,
            format!("specialization limit of {SPECIALIZATION_BUDGET} exceeded"),
        ));
    }
    seen.insert(specialization.clone());
    discovered.push(specialization.clone());
    active.push(specialization.clone());

    let function = &program.functions[specialization.0];
    let substitutions = substitutions(function, &specialization.1);
    let mut nested = Vec::new();
    if let Some(body) = &function.body {
        collect_specializations(body, &substitutions, program, &mut nested);
    }
    for (nested, nested_span) in nested {
        visit_specialization(nested, nested_span, program, active, seen, discovered)?;
    }
    active.pop();
    Ok(())
}

fn collect_specializations(
    statements: &[Statement],
    substitutions: &HashMap<String, Type>,
    program: &Program,
    discovered: &mut Vec<(Specialization, crate::lexer::Span)>,
) {
    for statement in statements {
        match statement {
            Statement::Let { value, .. }
            | Statement::Assign { value, .. }
            | Statement::Expression(value) => {
                collect_in_expression(value, substitutions, program, discovered);
            }
            Statement::Return(value) => {
                if let Some(value) = value {
                    collect_in_expression(value, substitutions, program, discovered);
                }
            }
            Statement::If {
                condition,
                then_body,
                else_body,
            } => {
                collect_in_expression(condition, substitutions, program, discovered);
                collect_specializations(then_body, substitutions, program, discovered);
                if let Some(else_body) = else_body {
                    collect_specializations(else_body, substitutions, program, discovered);
                }
            }
            Statement::For { condition, body } => {
                collect_in_expression(condition, substitutions, program, discovered);
                if !matches!(&condition.kind, ExpressionKind::Boolean(false)) {
                    collect_specializations(body, substitutions, program, discovered);
                }
            }
        }
    }
}

fn collect_in_expression(
    expression: &Expression,
    substitutions: &HashMap<String, Type>,
    program: &Program,
    discovered: &mut Vec<(Specialization, crate::lexer::Span)>,
) {
    match &expression.kind {
        ExpressionKind::DirectCall {
            function,
            type_arguments,
            arguments,
        } => {
            if !program.functions[*function].type_parameters.is_empty() {
                discovered.push((
                    (
                        *function,
                        type_arguments
                            .iter()
                            .map(|argument| argument.substitute(substitutions))
                            .collect(),
                    ),
                    expression.span,
                ));
            }
            for argument in arguments {
                collect_in_expression(argument, substitutions, program, discovered);
            }
        }
        ExpressionKind::IndirectCall { callee, arguments } => {
            collect_in_expression(callee, substitutions, program, discovered);
            for argument in arguments {
                collect_in_expression(argument, substitutions, program, discovered);
            }
        }
        ExpressionKind::Tuple(values) | ExpressionKind::Array(values) => {
            for value in values {
                collect_in_expression(value, substitutions, program, discovered);
            }
        }
        ExpressionKind::Index { base, index }
        | ExpressionKind::Binary {
            left: base,
            right: index,
            ..
        } => {
            collect_in_expression(base, substitutions, program, discovered);
            collect_in_expression(index, substitutions, program, discovered);
        }
        ExpressionKind::Unary { operand, .. } => {
            collect_in_expression(operand, substitutions, program, discovered);
        }
        ExpressionKind::Integer(_)
        | ExpressionKind::Boolean(_)
        | ExpressionKind::Local(_)
        | ExpressionKind::Function(_) => {}
    }
}

fn substitutions(function: &Function, arguments: &[Type]) -> HashMap<String, Type> {
    function
        .type_parameters
        .iter()
        .cloned()
        .zip(arguments.iter().cloned())
        .collect()
}

fn specialized_symbol(function: &Function, arguments: &[Type]) -> String {
    format!(
        "{}${}",
        function.name,
        arguments
            .iter()
            .map(type_symbol)
            .collect::<Vec<_>>()
            .join("$")
    )
}

fn type_symbol(value_type: &Type) -> String {
    match value_type {
        Type::I8 => "i8".to_owned(),
        Type::I16 => "i16".to_owned(),
        Type::I32 => "i32".to_owned(),
        Type::I64 => "i64".to_owned(),
        Type::U8 => "u8".to_owned(),
        Type::U16 => "u16".to_owned(),
        Type::U32 => "u32".to_owned(),
        Type::U64 => "u64".to_owned(),
        Type::Bool => "bool".to_owned(),
        Type::Void => "void".to_owned(),
        Type::Tuple(elements) => format!(
            "tuple{}_{}",
            elements.len(),
            elements
                .iter()
                .map(type_symbol)
                .collect::<Vec<_>>()
                .join("_")
        ),
        Type::Array(element, length) => format!("array_{}_{}", type_symbol(element), length),
        Type::Pointer(inner) => format!("pointer_{}", type_symbol(inner)),
        Type::Linear(inner) => format!("linear_{}", type_symbol(inner)),
        Type::Function(parameters, result) => format!(
            "fn{}_{}_to_{}",
            parameters.len(),
            parameters
                .iter()
                .map(type_symbol)
                .collect::<Vec<_>>()
                .join("_"),
            type_symbol(result)
        ),
        Type::Parameter(name) => name.clone(),
    }
}
